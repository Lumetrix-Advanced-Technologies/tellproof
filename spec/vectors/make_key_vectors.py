"""Key-status vectors: which JWKS keys may vouch for a pack (D-042).

Writes spec/vectors/keys/*.jwks.json and spec/vectors/key-manifest.json. No pack is
signed or changed: every case checks an existing pass vector against a different
JWKS. Rules every verifier applies after the signature verifies:

  - nbf / exp (JWT NumericDate seconds) bound when the key may sign: the pack's
    issued_at, in whole seconds, must satisfy nbf <= issued_at < exp;
  - a kid listed in "revoked" vouches for nothing, whatever the pack's issued_at,
    because whoever holds a compromised key can backdate it.

expect is a result object, or "jwks_error": the JWKS itself is malformed and every
verifier must refuse to load it.

Run from the repo root:  python3 spec/vectors/make_key_vectors.py
"""
import json
from datetime import datetime
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric import ec

OUT = Path(__file__).resolve().parent
KEYS = OUT / "keys"
BASE = json.loads((OUT / "test-jwks.json").read_text())["keys"][0]
KID = BASE["kid"]
PACK = "pass/KST-CTA-0001.dsse.json"
ISSUED = int(datetime.fromisoformat("2026-08-12T09:00:00+10:00").timestamp())  # 1786489200, pack 1's issued_at

# A second, unrelated key (fixed scalar) for rotation cases. It signs nothing.
other = ec.derive_private_key(0x5EED_0F_0DD_C0FFEE_0042, ec.SECP256R1()).public_key().public_numbers()
b64u = lambda i: __import__("base64").urlsafe_b64encode(i.to_bytes(32, "big")).rstrip(b"=").decode()  # noqa: E731
NEXT = {"kty": "EC", "crv": "P-256", "kid": "test-p256-2027-01", "use": "sig", "alg": "ES256", "x": b64u(other.x), "y": b64u(other.y)}

OK = {"signature": True, "subject_digest": True, "chain": None, "merkle": True, "verified": True}
REFUSED = {"signature": False, "subject_digest": True, "chain": None, "merkle": True, "verified": False}


def key(**extra):
    return {**BASE, **extra}


CASES = [
    ("window-covers-issue", {"keys": [key(nbf=ISSUED - 86400, exp=ISSUED + 86400)]}, OK,
     "issued inside the key's validity window"),
    ("nbf-equals-issue", {"keys": [key(nbf=ISSUED)]}, OK, "nbf is inclusive"),
    ("not-yet-valid", {"keys": [key(nbf=ISSUED + 1)]}, REFUSED, "issued one second before the key's nbf"),
    ("expired-at-issue", {"keys": [key(exp=ISSUED)]}, REFUSED, "exp is exclusive: a pack issued at exp is refused"),
    ("rotated-after-issue", {"keys": [key(exp=ISSUED + 1), {**NEXT, "nbf": ISSUED + 1}]}, OK,
     "the key was retired after the pack was issued: old packs still verify after rotation"),
    ("revoked", {"keys": [key()], "revoked": [{"kid": KID, "revoked_at": ISSUED + 30 * 86400, "reason": "test: key compromise"}]}, REFUSED,
     "a revoked key vouches for nothing, even for packs dated before the revocation"),
    ("other-key-revoked", {"keys": [key(), NEXT], "revoked": [{"kid": NEXT["kid"], "revoked_at": ISSUED}]}, OK,
     "revoking another key does not affect this one"),
    # Malformed sets: refuse to load the JWKS at all.
    ("nbf-not-a-number", {"keys": [key(nbf=str(ISSUED))]}, "jwks_error", "nbf must be an integer NumericDate"),
    ("exp-before-nbf", {"keys": [key(nbf=ISSUED, exp=ISSUED)]}, "jwks_error", "exp must be after nbf"),
    ("fractional-exp", {"keys": [key(exp=ISSUED + 0.5)]}, "jwks_error", "NumericDates here are whole seconds"),
    ("revoked-without-time", {"keys": [key()], "revoked": [{"kid": KID}]}, "jwks_error", "a revocation needs revoked_at"),
    ("revoked-unknown-member", {"keys": [key()], "revoked": [{"kid": KID, "revoked_at": ISSUED, "by": "x"}]}, "jwks_error",
     "revocation entries have kid, revoked_at and an optional reason only"),
    ("unknown-top-level", {"keys": [key()], "expires": ISSUED}, "jwks_error", "a JWKS has keys and revoked only"),
    ("unknown-key-member", {"keys": [key(iat=ISSUED)]}, "jwks_error", "key members are the ES256 JWK members plus nbf and exp"),
]


def main():
    KEYS.mkdir(exist_ok=True)
    cases = []
    for name, jwks, expect, why in CASES:
        path = KEYS / f"{name}.jwks.json"
        path.write_text(json.dumps(jwks, indent=2) + "\n")
        cases.append({"name": name, "file": PACK, "jwks": f"keys/{name}.jwks.json", "prev": None, "expect": expect, "why": why})
    manifest = {"version": 1, "issued_at_seconds": ISSUED,
                "note": "Key-status cases (D-042): the same pass vector against different JWKS files. expect is a result object, "
                        "or \"jwks_error\": the JWKS is malformed and must not load. Generated by make_key_vectors.py.",
                "cases": cases}
    (OUT / "key-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {len(cases)} key-status cases")


if __name__ == "__main__":
    main()
